import crypto from 'crypto';
import { config } from '../config/env';

export interface CreateOrderParams {
  amountPaise: number;
  currency?: string;
  receipt: string;
  notes?: Record<string, string>;
}

export interface RazorpayOrderResult {
  id: string;
  amount: number;
  currency: string;
  receipt: string;
  status: string;
  created_at?: number;
}

export interface RazorpayPaymentResult {
  id: string;
  order_id: string;
  amount: number;
  currency: string;
  status: string;
  method?: string;
  captured?: boolean;
  error_code?: string;
  error_description?: string;
  amount_refunded?: number;
  refund_status?: string | null;
}

export interface CreateRefundParams {
  amountPaise?: number;
  notes?: Record<string, string>;
  receipt?: string;
}

export interface RazorpayRefundResult {
  id: string;
  payment_id: string;
  amount: number;
  currency: string;
  status: string;
  created_at?: number;
}

/**
 * Razorpay Payment Gateway Service
 * Interacts with Razorpay REST APIs in TEST MODE using Basic Auth.
 * Includes cryptographic HMAC SHA256 signature verification and timing-safe comparisons.
 */
class RazorpayService {
  private get baseUrl(): string {
    return 'https://api.razorpay.com/v1';
  }

  private get authHeader(): string {
    const creds = `${config.razorpayKeyId}:${config.razorpayKeySecret}`;
    return `Basic ${Buffer.from(creds).toString('base64')}`;
  }

  private isMockMode(): boolean {
    return (
      process.env.NODE_ENV === 'test' ||
      config.razorpayKeyId.includes('placeholder') ||
      config.razorpayKeySecret.includes('placeholder')
    );
  }

  /**
   * Creates a new Razorpay Order on the server.
   */
  async createOrder(params: CreateOrderParams): Promise<RazorpayOrderResult> {
    const { amountPaise, currency = 'INR', receipt, notes = {} } = params;

    if (this.isMockMode()) {
      const mockOrderId = `order_test_${Date.now()}_${crypto.randomBytes(4).toString('hex')}`;
      return {
        id: mockOrderId,
        amount: amountPaise,
        currency,
        receipt,
        status: 'created',
        created_at: Math.floor(Date.now() / 1000),
      };
    }

    const res = await fetch(`${this.baseUrl}/orders`, {
      method: 'POST',
      headers: {
        Authorization: this.authHeader,
        'Content-Type': 'application/json',
      },
      body: JSON.stringify({
        amount: amountPaise,
        currency,
        receipt,
        notes,
      }),
    });

    if (!res.ok) {
      const errText = await res.text();
      let parsedErr: any = {};
      try {
        parsedErr = JSON.parse(errText);
      } catch {
        parsedErr = { message: errText };
      }
      throw new Error(
        `Razorpay order creation failed (HTTP ${res.status}): ${
          parsedErr.error?.description || parsedErr.message || errText
        }`
      );
    }

    return (await res.json()) as RazorpayOrderResult;
  }

  /**
   * Fetches payment details from Razorpay to verify status directly with gateway.
   */
  async fetchPayment(paymentId: string): Promise<RazorpayPaymentResult> {
    if (this.isMockMode()) {
      const mockOverride = (this as any)._mockPayment || {};
      return {
        id: paymentId,
        order_id: `order_mock_${paymentId}`,
        amount: 49900,
        currency: 'INR',
        status: 'captured',
        method: 'upi',
        captured: true,
        amount_refunded: 0,
        refund_status: null,
        ...mockOverride,
      };
    }

    const res = await fetch(`${this.baseUrl}/payments/${paymentId}`, {
      method: 'GET',
      headers: {
        Authorization: this.authHeader,
      },
    });

    if (!res.ok) {
      const errText = await res.text();
      throw new Error(`Razorpay fetch payment failed (HTTP ${res.status}): ${errText}`);
    }

    return (await res.json()) as RazorpayPaymentResult;
  }

  /**
   * Verifies the cryptographic HMAC SHA256 payment signature generated by Razorpay Checkout.
   * Format: HMAC-SHA256(order_id + "|" + payment_id, secret) == signature
   */
  verifyPaymentSignature(orderId: string, paymentId: string, signature: string): boolean {
    if (!orderId || !paymentId || !signature) {
      return false;
    }

    const secret = config.razorpayKeySecret;
    const expected = crypto
      .createHmac('sha256', secret)
      .update(`${orderId}|${paymentId}`)
      .digest('hex');

    if (expected.length !== signature.length) {
      return false;
    }

    try {
      return crypto.timingSafeEqual(
        Buffer.from(expected, 'utf8'),
        Buffer.from(signature, 'utf8')
      );
    } catch {
      return false;
    }
  }

  /**
   * Verifies the cryptographic HMAC SHA256 webhook signature.
   * Format: HMAC-SHA256(rawRequestBody, webhookSecret) == x-razorpay-signature
   */
  verifyWebhookSignature(rawBody: string | Buffer, signature: string): boolean {
    if (!rawBody || !signature) {
      return false;
    }

    const secret = config.razorpayWebhookSecret;
    const bodyStr = Buffer.isBuffer(rawBody) ? rawBody : Buffer.from(rawBody, 'utf8');

    const expected = crypto
      .createHmac('sha256', secret)
      .update(bodyStr)
      .digest('hex');

    if (expected.length !== signature.length) {
      return false;
    }

    try {
      return crypto.timingSafeEqual(
        Buffer.from(expected, 'utf8'),
        Buffer.from(signature, 'utf8')
      );
    } catch {
      return false;
    }
  }

  /**
   * Creates a refund for a captured payment.
   */
  async createRefund(paymentId: string, params: CreateRefundParams): Promise<RazorpayRefundResult> {
    const { amountPaise, notes = {}, receipt } = params;

    if (this.isMockMode()) {
      const mockStatus = (this as any)._mockRefundStatus || 'processed';
      return {
        id: `rfnd_test_${Date.now()}_${crypto.randomBytes(4).toString('hex')}`,
        payment_id: paymentId,
        amount: amountPaise || 49900,
        currency: 'INR',
        status: mockStatus,
        created_at: Math.floor(Date.now() / 1000),
      };
    }

    const body: Record<string, any> = { notes };
    if (typeof amountPaise === 'number' && amountPaise > 0) {
      body.amount = amountPaise;
    }
    if (receipt) {
      body.receipt = receipt;
    }

    const res = await fetch(`${this.baseUrl}/payments/${paymentId}/refund`, {
      method: 'POST',
      headers: {
        Authorization: this.authHeader,
        'Content-Type': 'application/json',
      },
      body: JSON.stringify(body),
    });

    if (!res.ok) {
      const errText = await res.text();
      let parsedErr: any = {};
      try {
        parsedErr = JSON.parse(errText);
      } catch {
        parsedErr = { message: errText };
      }
      throw new Error(
        `Razorpay refund failed (HTTP ${res.status}): ${
          parsedErr.error?.description || parsedErr.message || errText
        }`
      );
    }

    return (await res.json()) as RazorpayRefundResult;
  }
}

export const razorpayService = new RazorpayService();
